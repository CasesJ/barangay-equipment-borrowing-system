-- Barangay Equipment Borrowing System: Supabase/Postgres schema.
-- Run this in Supabase Dashboard > SQL Editor before starting the Flask app.

create table if not exists public.users (
  user_id bigint generated by default as identity primary key,
  full_name text not null check (length(trim(full_name)) > 0),
  username text not null check (length(trim(username)) > 0),
  password text not null,
  contact_number text,
  address text,
  email text not null check (length(trim(email)) > 0),
  role text not null default 'Staff' check (role in ('Admin', 'Staff')),
  status text not null default 'Active' check (status in ('Active', 'Inactive')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create unique index if not exists users_username_ci_key on public.users (lower(username));
create unique index if not exists users_email_ci_key on public.users (lower(email));

create table if not exists public.borrowers (
  borrower_id bigint generated by default as identity primary key,
  user_id bigint unique references public.users(user_id) on delete set null,
  full_name text not null check (length(trim(full_name)) > 0),
  contact_number text,
  address text,
  email text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.equipment (
  equipment_id bigint generated by default as identity primary key,
  equipment_name text not null check (length(trim(equipment_name)) > 0),
  category text not null check (length(trim(category)) > 0),
  total_stock integer not null check (total_stock >= 0),
  available_stock integer not null check (available_stock >= 0 and available_stock <= total_stock),
  unit_type text not null check (length(trim(unit_type)) > 0),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create unique index if not exists equipment_name_ci_key on public.equipment (lower(equipment_name));

create table if not exists public.borrowings (
  borrowing_id bigint generated by default as identity primary key,
  borrower_id bigint not null references public.borrowers(borrower_id) on delete restrict,
  processed_by bigint references public.users(user_id) on delete set null,
  borrowed_at timestamptz not null default now(),
  date_needed date,
  expected_return_date date not null,
  purpose_notes text,
  additional_notes text,
  status text not null default 'Pending' check (status in ('Pending', 'Approved', 'Rejected', 'Cancelled', 'Active', 'Partially Returned', 'Returned')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  check (expected_return_date >= date_needed or date_needed is null)
);

create table if not exists public.borrowing_items (
  borrowing_item_id bigint generated by default as identity primary key,
  borrowing_id bigint not null references public.borrowings(borrowing_id) on delete cascade,
  equipment_id bigint not null references public.equipment(equipment_id) on delete restrict,
  quantity_borrowed integer not null check (quantity_borrowed > 0),
  quantity_returned integer not null default 0 check (quantity_returned >= 0 and quantity_returned <= quantity_borrowed),
  remaining_quantity integer not null check (remaining_quantity >= 0 and remaining_quantity <= quantity_borrowed),
  unique (borrowing_id, equipment_id),
  check (remaining_quantity = quantity_borrowed - quantity_returned)
);

create table if not exists public.return_records (
  return_record_id bigint generated by default as identity primary key,
  borrowing_item_id bigint not null references public.borrowing_items(borrowing_item_id) on delete cascade,
  received_by bigint references public.users(user_id) on delete set null,
  quantity_returned integer not null check (quantity_returned > 0),
  return_date date not null default current_date,
  notes text,
  created_at timestamptz not null default now()
);

create table if not exists public.audit_logs (
  audit_id bigint generated by default as identity primary key,
  user_id bigint references public.users(user_id) on delete set null,
  action text not null,
  table_name text not null,
  record_id bigint,
  description text not null,
  created_at timestamptz not null default now()
);

create index if not exists borrowings_borrower_status_idx on public.borrowings (borrower_id, status);
create index if not exists borrowings_status_created_idx on public.borrowings (status, created_at desc);
create index if not exists borrowing_items_equipment_idx on public.borrowing_items (equipment_id);
create index if not exists return_records_item_idx on public.return_records (borrowing_item_id);
create index if not exists audit_logs_created_idx on public.audit_logs (created_at desc);

create or replace function public.set_updated_at()
returns trigger
language plpgsql
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

drop trigger if exists users_set_updated_at on public.users;
create trigger users_set_updated_at before update on public.users
for each row execute function public.set_updated_at();

drop trigger if exists borrowers_set_updated_at on public.borrowers;
create trigger borrowers_set_updated_at before update on public.borrowers
for each row execute function public.set_updated_at();

drop trigger if exists equipment_set_updated_at on public.equipment;
create trigger equipment_set_updated_at before update on public.equipment
for each row execute function public.set_updated_at();

drop trigger if exists borrowings_set_updated_at on public.borrowings;
create trigger borrowings_set_updated_at before update on public.borrowings
for each row execute function public.set_updated_at();

-- The Flask backend connects as the database owner, while browser access uses
-- the publishable key. Lock down direct Data API access until explicit RLS
-- policies are written for a Supabase Auth client.
alter table public.users enable row level security;
alter table public.borrowers enable row level security;
alter table public.equipment enable row level security;
alter table public.borrowings enable row level security;
alter table public.borrowing_items enable row level security;
alter table public.return_records enable row level security;
alter table public.audit_logs enable row level security;

revoke all on all tables in schema public from anon, authenticated;
revoke all on all sequences in schema public from anon, authenticated;
